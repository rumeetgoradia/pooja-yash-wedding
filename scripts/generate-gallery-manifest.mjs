import fs from "fs";
import path from "path";
import { getPlaiceholder } from "plaiceholder";

// (No other imports need to change)
const galleryDir = path.join(process.cwd(), "public/gallery");
const outputDir = path.join(process.cwd(), "lib/data");
const outputFile = path.join(outputDir, "gallery-data.ts");

// Wrap the logic in an async function to use await
const generateManifest = async () => {
  console.log("🖼️  Generating gallery manifest with plaiceholders...");

  const files = fs.readdirSync(galleryDir);

  // Use Promise.all to handle all async image processing
  const images = await Promise.all(
    files
      .filter((file) => /\.(jpg|jpeg|png|webp)$/i.test(file))
      .map(async (file) => {
        const filePath = path.join(galleryDir, file);
        const fileBuffer = fs.readFileSync(filePath);

        // Get the base64 placeholder and image dimensions
        const { base64, metadata } = await getPlaiceholder(fileBuffer);

        return {
          src: `/gallery/${file}`,
          width: metadata.width,
          height: metadata.height,
          blurDataURL: base64,
        };
      }),
  );

  const content = `// This file is auto-generated by scripts/generate-gallery-manifest.mjs
  // Do not edit this file directly.

  export interface GalleryImage {
    src: string;
    width: number;
    height: number;
    blurDataURL: string; // <-- Add the new property to the type
  }

  export const galleryImages: GalleryImage[] = ${JSON.stringify(images, null, 2)};
  `;

  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  fs.writeFileSync(outputFile, content);

  console.log(
    `✅ Manifest generated successfully with ${images.length} plaiceholders.`,
  );
};

// Run the async function
generateManifest();
